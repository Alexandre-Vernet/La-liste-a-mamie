export const GROCERY_DICTIONARY: readonly string[] = GROCERY_CATEGORIES.flatMap(
  (category) => category.products,
);

export function suggestGroceryNames(query: string, max = MAX_SUGGESTIONS): string[] {
  const normalizedQuery = normalize(query);

  if (!normalizedQuery) {
    return [];
  }

  return GROCERY_DICTIONARY.filter((name) => normalize(name).includes(normalizedQuery)).slice(
    0,
    max,
  );
}

export function normalize(value: string): string {
  return value
    .trim()
    .toLocaleLowerCase('fr-FR')
    .replace(/œ/g, 'oe')
    .replace(/æ/g, 'ae')
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '');
}
