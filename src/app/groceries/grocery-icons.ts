const ICON_BY_NORMALIZED_NAME: ReadonlyMap<string, string> = new Map(
  PRODUCT_ICONS.map(([name, icon]) => [normalize(name), icon]),
);

const CATEGORY_BY_NORMALIZED_PRODUCT: ReadonlyMap<string, string> = new Map(
  GROCERY_CATEGORIES.flatMap((category) =>
    category.products.map((product) => [normalize(product), category.name] as const),
  ),
);

const PRODUCTS_BY_EMOJI: ReadonlyMap<string, readonly string[]> = buildProductsByEmoji();

function buildProductsByEmoji(): ReadonlyMap<string, readonly string[]> {
  const productsByEmoji = new Map<string, string[]>();

  for (const [name, icon] of PRODUCT_ICONS) {
    const products = productsByEmoji.get(icon);

    if (products) {
      products.push(name);
    } else {
      productsByEmoji.set(icon, [name]);
    }
  }

  return productsByEmoji;
}

export function productsByEmoji(query: string): readonly string[] {
  return PRODUCTS_BY_EMOJI.get(query.trim()) ?? [];
}

export function groceryIcon(name: string): string {
  const normalizedName = normalize(name);

  const specificIcon = ICON_BY_NORMALIZED_NAME.get(normalizedName);
  if (specificIcon) {
    return specificIcon;
  }

  const category = CATEGORY_BY_NORMALIZED_PRODUCT.get(normalizedName);
  if (category) {
    return CATEGORY_FALLBACK_ICONS[category] ?? DEFAULT_ICON;
  }

  return DEFAULT_ICON;
}
